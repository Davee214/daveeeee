CREATE DATABASE IF NOT EXISTS libflow CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE libflow;

CREATE TABLE IF NOT EXISTS books (
  id VARCHAR(30) PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  author VARCHAR(180) NOT NULL,
  isbn VARCHAR(30) NOT NULL,
  category VARCHAR(80) NOT NULL,
  copies INT NOT NULL DEFAULT 1,
  available INT NOT NULL DEFAULT 1,
  cover VARCHAR(4) NOT NULL DEFAULT 'L'
);

CREATE TABLE IF NOT EXISTS patrons (
  id VARCHAR(30) PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  email VARCHAR(180) NOT NULL,
  type VARCHAR(30) NOT NULL DEFAULT 'Student',
  card VARCHAR(30) NOT NULL DEFAULT 'Active',
  fines DECIMAL(10,2) NOT NULL DEFAULT 0,
  joined DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS loans (
  id VARCHAR(30) PRIMARY KEY,
  patron_id VARCHAR(30) NOT NULL,
  book_id VARCHAR(30) NOT NULL,
  checked_out DATE NOT NULL,
  due_date DATE NOT NULL,
  renewals INT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'Active',
  returned_at DATETIME NULL,
  FOREIGN KEY (patron_id) REFERENCES patrons(id),
  FOREIGN KEY (book_id) REFERENCES books(id)
);

CREATE TABLE IF NOT EXISTS audit_log (
  id VARCHAR(40) PRIMARY KEY,
  action VARCHAR(60) NOT NULL,
  detail VARCHAR(255) NOT NULL,
  user_name VARCHAR(100) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(30) PRIMARY KEY,
  patron_id VARCHAR(30) NULL,
  name VARCHAR(180) NOT NULL,
  email VARCHAR(180) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'Student',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (patron_id) REFERENCES patrons(id)
);

CREATE TABLE IF NOT EXISTS reservations (
  id VARCHAR(40) PRIMARY KEY,
  patron_id VARCHAR(30) NOT NULL,
  book_id VARCHAR(30) NOT NULL,
  reserved_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at DATETIME NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Pending',
  FOREIGN KEY (patron_id) REFERENCES patrons(id),
  FOREIGN KEY (book_id) REFERENCES books(id)
);
